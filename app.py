    data = request.get_json(silent=True) or {}
    url = (data.get("url") or "").strip()
    cookies = data.get("cookies") or ""
    gear_index = data.get("gear_index")

    if not url:
        return jsonify(ok=False, code="bad_url", error="Enter a TikTok video URL.")
    if not cookies.strip():
        return jsonify(
            ok=False,
            code="no_cookies",
            error="Paste your tiktok.com cookies first.",
        )

    try:
        gear_index = int(gear_index) if gear_index is not None else None
    except (TypeError, ValueError):
        gear_index = None

    job_id = new_job(url, cookies, gear_index)
    return jsonify(ok=True, job_id=job_id)


