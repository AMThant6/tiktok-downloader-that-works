def _walk_lists(obj, key):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k == key and isinstance(v, list):
                yield v
            yield from _walk_lists(v, key)
    elif isinstance(obj, list):
        for item in obj:
            yield from _walk_lists(item, key)


def _walk_video_items(obj, out):
    if isinstance(obj, dict):
        vid = obj.get("video")
        if isinstance(vid, dict) and "bitrateInfo" in vid and "id" in obj:
            out.append(obj)
        for v in obj.values():
            _walk_video_items(v, out)
    elif isinstance(obj, list):
        for item in obj:
            _walk_video_items(item, out)


REHYDRATION_ID = "__UNIVERSAL_DATA_FOR_REHYDRATION__"


def _rehydration_from_html(html):
    """Pull the rehydration JSON out of the rendered document.

    Regular video pages are server-rendered: the item data sits in a
    <script id="__UNIVERSAL_DATA_FOR_REHYDRATION__"> tag and there may be no
    matching XHR at all, so reading the DOM is the primary path here.
    """
    if not html or REHYDRATION_ID not in html:
        return None
    m = re.search(
        r'<script[^>]*id="' + REHYDRATION_ID + r'"[^>]*>(.*?)</script>',
        html,
        re.S,
    )
    if not m:
        return None
    try:
        return json.loads(m.group(1))
    except Exception:
        return None


def _collect_episodes(data, episodes, seen_ids):
    """Merge every itemList in a JSON tree into {episode_number: entry}."""
    for item_list in _walk_lists(data, "itemList"):
        for entry in item_list:
            if not isinstance(entry, dict):
                continue
            eid = str(entry.get("id") or "")
            if eid and eid in seen_ids:
                continue
            info = entry.get("dramaInfo") or {}
            video_data = info.get("DramaVideoData") or {}
            try:
                ep_num = int(video_data.get("EpisodeNumber") or 0)
            except (TypeError, ValueError):
                ep_num = 0
            if not ep_num:
                continue
            if eid:
                seen_ids.add(eid)
            episodes[ep_num] = {
                "entry": entry,
                "drama_name": info.get("dramaName") or "",
            }
    return len(episodes)


def _codec_info(codec):
    """Normalise TikTok's codec strings into (label, is_hevc, short_token).

    TikTok has shipped several spellings for the same two codecs, so both the
    HEVC and H.264 families are matched loosely.
    """
    c = str(codec or "").strip().lower()
    if not c:
        return "unknown", False, "unknown"
    if c in ("h264", "avc", "avc1"):
        return "H.264 (h264)", False, "h264"
    if c in ("bytevc1", "h265_hvc1", "h265", "hevc", "hvc1"):
        return f"HEVC ({c})", True, "hevc"
    return c, False, c


def _parse_gears(video):
    """Turn video.bitrateInfo into a normalised gear list, best last."""
    gears = []
    duration = 0
    try:
        duration = int(video.get("duration") or 0)
    except (TypeError, ValueError):
        duration = 0

    for g in video.get("bitrateInfo") or []:
        if not isinstance(g, dict):
            continue
        play = g.get("PlayAddr") or {}
        if not isinstance(play, dict):
            continue
        urls = play.get("UrlList") or []
        url = next((u for u in urls if isinstance(u, str) and u.startswith("http")), None)
        if not url:
            continue

        def _int(v):
            # DataSize and friends sometimes arrive as numeric strings.
            try:
                return int(float(v))
            except (TypeError, ValueError):
                return 0

        width = _int(play.get("Width"))
        height = _int(play.get("Height"))
        # Bitrate is bits per second, not kbps.
        bitrate = _int(g.get("Bitrate"))
        size = _int(play.get("DataSize"))
        if not size and bitrate and duration:
            size = int(bitrate / 8 * duration)

        codec_label, is_hevc, codec_short = _codec_info(g.get("CodecType"))
        gears.append(
            {
                "url": url,
                "width": width,
                "height": height,
                "bitrate": bitrate,
                "kbps": round(bitrate / 1000) if bitrate else 0,
                "codec": str(g.get("CodecType") or "").lower() or "unknown",
                "codec_label": codec_label,
                "codec_short": codec_short,
                "is_hevc": is_hevc,
                "size": size,
                "gear_name": str(g.get("GearName") or ""),
            }
        )

    if not gears:
        # Last resort: a bare playAddr / downloadAddr with no gear metadata.
        for field in ("downloadAddr", "playAddr"):
            cand = video.get(field)
            if isinstance(cand, str) and cand.startswith("http"):
                bitrate = int(video.get("bitrate") or 0)
                size = int(bitrate / 8 * duration) if (bitrate and duration) else 0
                codec_label, is_hevc, codec_short = _codec_info(video.get("codecType"))
                gears.append(
                    {
                        "url": cand,
                        "width": int(video.get("width") or 0),
                        "height": int(video.get("height") or 0),
                        "bitrate": bitrate,
                        "kbps": round(bitrate / 1000) if bitrate else 0,
                        "codec": str(video.get("codecType") or "").lower() or "unknown",
                        "codec_label": codec_label,
                        "codec_short": codec_short,
                        "is_hevc": is_hevc,
                        "size": size,
                        "gear_name": "",
                    }
                )
                break

    # Collapse duplicates of the same resolution+codec, keeping the richest.
    dedup = {}
    for g in gears:
        k = (g["width"], g["height"], g["codec"])
        if k not in dedup or g["bitrate"] > dedup[k]["bitrate"]:
            dedup[k] = g
    gears = list(dedup.values())

    gears.sort(key=lambda g: (g["width"] * g["height"], g["bitrate"]))
    for i, g in enumerate(gears):
        g["index"] = i
    return gears


def _best_index(gears):
    if not gears:
        return 0
    return max(
        range(len(gears)),
        key=lambda i: (gears[i]["width"] * gears[i]["height"], gears[i]["bitrate"]),
    )


def _clean(s, limit=None):
    s = re.sub(r"\s+", " ", str(s or "")).strip()
    s = "".join(ch for ch in s if ch >= " " and ch not in ILLEGAL_CHARS)
    s = s.strip().rstrip(".")
    if limit and len(s) > limit:
        s = s[:limit].rstrip()
    return s


def capture(url, cookies_text, key):
    """Open Chrome with the user's cookies and scrape the bitrate metadata."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        raise AppError(
            "Playwright is not installed. Run: pip install -r requirements.txt",
            "no_playwright",
        )

    cookies = parse_cookies(cookies_text)[0]
    jar_path = write_jar(cookies_text, key)

    captured = []          # (url, text)
    pending_responses = []  # bodies that failed to read on the first pass

    with sync_playwright() as p:
        try:
            browser = p.chromium.launch(
                channel="chrome",
                headless=True,
                args=[
                    "--disable-blink-features=AutomationControlled",
                    "--no-first-run",
                    "--no-default-browser-check",
                ],
            )
        except Exception as exc:
            raise AppError(
                "Could not launch Google Chrome. Make sure Chrome is installed "
                f"(Playwright launches your existing install). Details: {exc}",
                "no_chrome",
            )

        try:
            context = browser.new_context(
                user_agent=DESKTOP_UA,
                viewport={"width": 1440, "height": 900},
                locale="en-US",
                timezone_id="America/New_York",
            )
            try:
                context.add_cookies(cookies)
            except Exception as exc:
                raise AppError(
                    "Chrome rejected the supplied cookies - the export looks "
                    f"malformed. Re-export cookies.txt and try again. Details: {exc}",
                    "bad_cookies",
                )

            page = context.new_page()

            def on_response(resp):
                u = resp.url
                if "/api/drama/" in u or "/api/item/detail/" in u:
                    try:
                        captured.append((u, resp.text()))
                    except Exception:
                        pending_responses.append(resp)

            page.on("response", on_response)

            try:
                page.goto(url, wait_until="domcontentloaded", timeout=60000)
            except Exception as exc:
                raise AppError(
                    f"Could not open that URL: {exc}", "nav_failed"
                )

            # Let the page settle. Drama pages need to wait for the item_list
            # XHR; regular video pages are server-rendered, so a flat floor is
            # all they need (waiting for an XHR that never fires just wastes
            # 30 extra seconds).
            is_drama = "/shortdrama/" in url
            started = time.time()
            while True:
                elapsed = time.time() - started
                if is_drama:
                    if (captured and elapsed >= SETTLE_FLOOR) or elapsed >= SETTLE_CEILING:
                        break
                elif elapsed >= SETTLE_FLOOR:
                    break
                page.wait_for_timeout(400)

            for resp in pending_responses:
                try:
                    captured.append((resp.url, resp.text()))
                except Exception:
                    pass

            final_url = page.url

            # A logged-out session gets bounced from /shortdrama/episode/... to
            # /foryou. That is a cookie problem, not a "video missing" problem.
            if "/foryou" in final_url and "/foryou" not in url:
                raise AppError(
                    "TikTok redirected to the For You feed, which means the "
                    "session was not recognised. Re-export cookies.txt while "
                    "logged in and paste the fresh export.",
                    "session_expired",
                )

            try:
                html = page.content()
            except Exception:
                html = ""
            rehydration = _rehydration_from_html(html)

            drama_match = re.search(
                r"/shortdrama/episode/(\d+)/(\d+)", url
            )

            if drama_match:
                info = _capture_drama(
                    page, captured, rehydration, drama_match, final_url
                )
            else:
                info = _capture_video(captured, rehydration, final_url, url)

            if not info["gears"]:
                raise AppError(
                    "Found the video but no downloadable qualities. The post may "
                    "be private, region-locked, or removed.",
                    "no_gears",
                )

            info["jar"] = jar_path
            info["best_index"] = _best_index(info["gears"])
            return info

        finally:
            try:
                browser.close()
            except Exception:
                pass


def _capture_drama(page, captured, rehydration, drama_match, final_url):
    """Parse /api/drama/episode/item_list/ payloads, scrolling if needed."""
    drama_id, want_ep = drama_match.group(1), int(drama_match.group(2))
    episodes = {}
    seen_ids = set()
    stall = 0

    def harvest():
        if rehydration:
            _collect_episodes(rehydration, episodes, seen_ids)
        for u, body in list(captured):
            if "/api/drama/" not in u:
                continue
            try:
                data = json.loads(body)
            except Exception:
                continue
            _collect_episodes(data, episodes, seen_ids)
        return len(episodes)

    for _round in range(SCROLL_ROUNDS):
        before = harvest()

        if want_ep in episodes:
            break

        if len(episodes) == before:
            stall += 1
            if stall >= SCROLL_STALL:
                break
        else:
            stall = 0

        try:
            page.mouse.wheel(0, 3000)
            page.wait_for_timeout(1200)
        except Exception:
            break

    if want_ep not in episodes:
        if episodes:
            raise AppError(
                f"Episode {want_ep} was not in the loaded list "
                f"({len(episodes)} episode(s) found). Double-check the episode "
                "number in the URL.",
                "no_video",
            )
        raise AppError(
            "No episode data came back for that drama. The link may be wrong, "
            "or the session may have expired - try re-exporting cookies.",
            "no_video",
        )

    chosen = episodes[want_ep]
    entry = chosen["entry"]
    video = entry.get("video") or {}
    gears = _parse_gears(video)

    drama_name = _clean(chosen["drama_name"]) or f"Drama {drama_id}"
    desc = _clean(entry.get("desc"), limit=80)
    title = f"{drama_name} EP{want_ep}"
    if desc:
        title += f" - {desc}"

    return {
        "kind": "drama",
        "title": title,
        "drama_name": drama_name,
        "episode": want_ep,
        "desc": desc,
        "gears": gears,
    }


def _capture_video(captured, rehydration, final_url, requested_url):
    """Find the item carrying bitrateInfo, from the DOM or any captured JSON."""
    items = []

    # Primary path: the server-rendered rehydration blob.
    if rehydration:
        _walk_video_items(rehydration, items)

    # Secondary path: an /api/item/detail/ XHR, when the page fires one.
    for _u, body in list(captured):
        try:
            data = json.loads(body)
        except Exception:
            continue
        _walk_video_items(data, items)

    # Last resort: a captured body that embeds the blob as HTML text.
    if not items:
        for _u, body in list(captured):
            nested = _rehydration_from_html(body)
            if nested:
                _walk_video_items(nested, items)

    if not items:
        raise AppError(
            "No video data came back for that URL. It may be a photo post, "
            "private, or the session may have expired.",
            "no_video",
        )

    # Prefer the item whose id appears in the URL.
    id_match = re.search(r"/video/(\d+)", requested_url or "")
    want_id = id_match.group(1) if id_match else ""
    item = next((i for i in items if str(i.get("id")) == want_id), items[0])

    video = item.get("video") or {}
    gears = _parse_gears(video)

    desc = _clean(item.get("desc"), limit=80)
    author = ""
    au = item.get("author") or {}
    if isinstance(au, dict):
        author = _clean(au.get("uniqueId") or au.get("nickname") or "", limit=40)

    title = desc or (f"@{author} video {item.get('id')}" if author else f"Video {item.get('id')}")
    if desc and author:
        title = f"@{author} - {desc}"

    return {
        "kind": "video",
        "title": title,
        "drama_name": "",
        "episode": None,
        "desc": desc,
        "gears": gears,
    }


