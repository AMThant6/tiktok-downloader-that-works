def build_filename(info, gear):
    """Build "{dramaName} EP{n} {desc} {w}x{h} {codec}.mp4".

    The drama parts are skipped for regular videos. The descriptive head is
    truncated against a budget so the trailing resolution/codec - the useful
    bits when telling files apart - never get cut off by the length cap.
    """
    res = f"{gear['width']}x{gear['height']}" if gear["width"] and gear["height"] else ""
    codec = gear.get("codec_short") or gear.get("codec") or ""
    if codec == "unknown":
        codec = ""

    tail = " ".join(p for p in (res, codec) if p)
    budget = 150 - len(tail) - 1  # room for the joining space

    if info["kind"] == "drama" and info.get("drama_name"):
        head = _clean(info["drama_name"]) or "drama"
        if info.get("episode"):
            head += f" EP{info['episode']}"
        desc = _clean(info.get("desc"))
        if desc:
            head += f" {desc}"
    else:
        head = _clean(info.get("desc")) or _clean(info.get("title")) or "tiktok"

    if len(head) > budget:
        head = head[:budget].rstrip()

    name = " ".join(p for p in (head, tail) if p)
    return _clean(name, limit=150) + ".mp4"


def run_curl(job, gear_url, jar_path, dest):
    """Run curl.exe with resume + retries, reporting progress while it goes."""
    cmd = [
        CURL,
        "--http1.1",
        "-L",
        "-s",
        "--retry", "5",
        "--retry-all-errors",
        "--retry-delay", "2",
        "-C", "-",
        "-b", jar_path,
        "-A", DESKTOP_UA,
        "-H", "Referer: https://www.tiktok.com/",
        "-o", str(dest),
        "-w", "%{http_code}",
        gear_url,
    ]

    creationflags = 0
    if os.name == "nt":
        creationflags = getattr(subprocess, "CREATE_NO_WINDOW", 0)

    expected = job.get("expected", 0)
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        creationflags=creationflags,
    )

    while proc.poll() is None:
        try:
            size = dest.stat().st_size if dest.exists() else 0
        except OSError:
            size = 0
        job["done_bytes"] = size
        if expected:
            job["progress"] = min(99.0, size / expected * 100.0)
        else:
            job["progress"] = 0.0
        time.sleep(0.5)

    try:
        out, err = proc.communicate(timeout=30)
    except subprocess.TimeoutExpired:
        proc.kill()
        out, err = proc.communicate()

    stdout = (out or b"").decode("utf-8", "replace").strip()
    stderr = (err or b"").decode("utf-8", "replace").strip()

    code_match = re.search(r"(\d{3})\s*$", stdout)
    http_code = int(code_match.group(1)) if code_match else 0

    try:
        final_size = dest.stat().st_size if dest.exists() else 0
    except OSError:
        final_size = 0

    job["done_bytes"] = final_size
    return proc.returncode, http_code, stderr, final_size


def process_job(job):
    """Worker body: capture if needed, then download the requested gear."""
    try:
        url = job["url"]
        cookies = job["cookies"]

        job["status"] = "capturing"
        job["message"] = "Preparing…"

        def on_stage(msg):
            job["message"] = msg

        info, cached = get_or_capture(url, cookies, on_stage=on_stage)
        job["title"] = info["title"]
        job["cached"] = cached

        gears = info["gears"]
        idx = job["gear_index"]
        if idx is None or idx < 0 or idx >= len(gears):
            idx = info["best_index"]
        gear = gears[idx]
        job["gear"] = gear

        dest = DOWNLOADS / build_filename(info, gear)
        job["filename"] = dest.name
        job["expected"] = gear["size"] or 0

        # Already have a complete copy of this exact file? Nothing to do, but
        # still record the path so the Save button works.
        if dest.exists() and gear["size"] and dest.stat().st_size == gear["size"]:
            job["progress"] = 100.0
            job["done_bytes"] = dest.stat().st_size
            job["file_path"] = str(dest)
            job["status"] = "done"
            job["message"] = "This file was already in your Downloads folder."
            return

        job["status"] = "downloading"
        job["message"] = f"Downloading {dest.name}"

        DOWNLOADS.mkdir(parents=True, exist_ok=True)
        rc, http_code, stderr, size = run_curl(job, gear["url"], info["jar"], dest)

        job["http_code"] = http_code
        expected = gear["size"] or 0

        if http_code in (200, 206, 416) or rc == 0:
            if expected and size < expected * EXPECTED_TOLERANCE:
                job["status"] = "error"
                job["code"] = "incomplete"
                job["message"] = (
                    f"Download incomplete: got {size / 1048576:.1f} MB of about "
                    f"{expected / 1048576:.1f} MB. The connection was probably "
                    "reset - press Download again and curl will resume from "
                    "where it stopped."
                )
                return
            if size == 0:
                job["status"] = "error"
                job["code"] = "incomplete"
                job["message"] = (
                    "The download produced an empty file. The link has likely "
                    "expired - press Get qualities again to refresh it."
                )
                return

            job["progress"] = 100.0
            job["status"] = "done"
            job["message"] = f"Saved to {DOWNLOADS}"
            job["file_path"] = str(dest)
            return

        job["status"] = "error"
        job["code"] = "download_failed"
        if http_code == 403:
            job["message"] = (
                "The CDN refused the download (HTTP 403). Your cookies have "
                "most likely expired - re-export cookies.txt and try again."
            )
        elif http_code == 404:
            job["message"] = (
                "The video URL returned HTTP 404. The link has probably expired "
                "- press Get qualities again to refresh it."
            )
        else:
            detail = f" (HTTP {http_code}, curl exit {rc})" if http_code else f" (curl exit {rc})"
            job["message"] = (
                "Download failed" + detail + "."
                + (f" {stderr[:200]}" if stderr else "")
            )

    except AppError as exc:
        job["status"] = "error"
        job["code"] = exc.code
        job["message"] = exc.message
    except Exception as exc:  # noqa: BLE001 - surface anything else to the UI
        job["status"] = "error"
        job["code"] = "error"
        job["message"] = f"Unexpected error: {exc}"


