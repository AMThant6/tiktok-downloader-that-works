CACHE = {}
CACHE_LOCK = threading.Lock()
CAPTURE_LOCK = threading.Lock()  # only one Chrome instance at a time


def get_or_capture(url, cookies_text, on_stage=None):
    """Return (info, was_cached). Reuses a recent capture for the same inputs."""
    key = cookie_key(url + "\x00" + cookies_text)

    with CACHE_LOCK:
        entry = CACHE.get(key)
        if entry and time.time() - entry["ts"] < CACHE_TTL:
            return entry["info"], True

    if on_stage:
        on_stage("Opening Chrome and loading your session…")

    with CAPTURE_LOCK:
        with CACHE_LOCK:
            entry = CACHE.get(key)
            if entry and time.time() - entry["ts"] < CACHE_TTL:
                return entry["info"], True

        info = capture(url, cookies_text, key)

        with CACHE_LOCK:
            CACHE[key] = {"ts": time.time(), "info": info}
        sweep_temp()
        return info, False


