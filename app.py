#!/usr/bin/env python3
"""
TikTok Downloader - local web app.

Downloads TikTok videos (regular posts and short-drama episodes) in the best
available quality by driving a real logged-in Chrome session with Playwright,
then pulling the chosen bitrate gear with curl.exe.

Why a browser instead of a plain HTTP client:
  On some networks/IPs the CDN answers "Your IP address is blocked from
  accessing this post" even when valid cookies are supplied. A real browser
  session with the user's cookies sidesteps that.

Why curl.exe instead of a Python HTTP client:
  TikTok CDNs break HTTP/2 in some Python stacks ("expected SETTINGS frame"),
  and connections get reset mid-download. curl.exe with --http1.1 plus
  resume (-C -) and retries handles both.

Run:  python app.py       (or .venv\\Scripts\\python app.py)
Then open http://127.0.0.1:5000
"""

