class AppError(Exception):
    """Carries a friendly message plus a machine-readable code for the UI."""

    def __init__(self, message, code="error"):
        super().__init__(message)
        self.message = message
        self.code = code


def _same_site(raw, secure):
    """Normalise a SameSite value into what Playwright/Chrome will accept."""
    s = str(raw or "").strip().lower()
    if s == "strict":
        return "Strict"
    if s in ("no_restriction", "none"):
        # Chrome rejects SameSite=None on an insecure cookie.
        return "None" if secure else "Lax"
    return "Lax"


def _build_cookies(entries):
    """Filter, dedupe and normalise raw cookie entries.

    `entries` is a list of dicts carrying name/value/domain/path/secure/
    httpOnly/expires/sameSite. Only domains containing "tiktok" survive,
    duplicates collapse on (domain, name) with the last occurrence winning,
    and expired cookies are dropped. Returns (playwright_cookies, jar_text).
    """
    now = time.time()
    by_key = {}
    order = []

    for e in entries:
        domain = str(e.get("domain") or "").strip()
        name = str(e.get("name") or "").strip()
        if "tiktok" not in domain.lower() or not name:
            continue

        try:
            expires = int(float(e.get("expires") or 0))
        except (TypeError, ValueError):
            expires = 0
        if expires and expires < now:
            continue  # already expired - would only confuse the session

        secure = bool(e.get("secure"))
        key = (domain, name)
        if key not in by_key:
            order.append(key)
        by_key[key] = {
            "name": name,
            "value": str(e.get("value") if e.get("value") is not None else ""),
            "domain": domain,
            "path": str(e.get("path") or "/"),
            "secure": secure,
            "httpOnly": bool(e.get("httpOnly")),
            "expires": expires if expires else -1,
            "sameSite": _same_site(e.get("sameSite"), secure),
        }

    if not by_key:
        raise AppError(
            "No usable tiktok.com cookies found in that export. Export them "
            "while logged in and make sure the file covers .tiktok.com (not "
            "just www.tiktok.com).",
            "no_cookies",
        )

    cookies = [by_key[k] for k in order]

    jar_lines = ["# Netscape HTTP Cookie File", "# Generated by TikTok Downloader", ""]
    for c in cookies:
        exp = int(c["expires"]) if c["expires"] != -1 else 0
        jar_lines.append(
            "\t".join(
                [
                    c["domain"],
                    "TRUE" if c["domain"].startswith(".") else "FALSE",
                    c["path"],
                    "TRUE" if c["secure"] else "FALSE",
                    str(exp),
                    c["name"],
                    c["value"],
                ]
            )
        )

    return cookies, "\n".join(jar_lines) + "\n"


def _parse_netscape(text):
    """Netscape cookies.txt rows -> raw entries."""
    entries = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue

        http_only = False
        if line.startswith("#HttpOnly_"):
            # Netscape spec: an HttpOnly cookie is commented out with a prefix.
            line = line[len("#HttpOnly_"):]
            http_only = True
        elif line.startswith("#"):
            continue

        parts = line.split("\t")
        if len(parts) < 7:
            # Some exporters use runs of spaces instead of tabs.
            parts = re.split(r"\s+", line, maxsplit=6)
        if len(parts) < 7:
            continue

        domain, _flag, path, secure, expires, name, value = parts[:7]
        entries.append(
            {
                "domain": domain,
                "path": path,
                "secure": secure.strip().upper() == "TRUE",
                "httpOnly": http_only,
                "expires": expires,
                "name": name,
                "value": value,
                "sameSite": "Lax",
            }
        )
    return entries


def _parse_json(text):
    """Cookie-Editor / EditThisCookie JSON array (or {"cookies": [...]}) -> raw entries."""
    try:
        data = json.loads(text)
    except Exception:
        return []

    if isinstance(data, dict):
        for key in ("cookies", "Cookies", "data"):
            if isinstance(data.get(key), list):
                data = data[key]
                break
        else:
            return []

    if not isinstance(data, list):
        return []

    entries = []
    for item in data:
        if not isinstance(item, dict) or "name" not in item:
            continue
        # A session cookie has no expiry and must be sent as -1 to Playwright.
        if item.get("session"):
            expires = 0
        else:
            expires = item.get("expirationDate") or item.get("expiration") or 0
        entries.append(
            {
                "domain": item.get("domain"),
                "path": item.get("path"),
                "secure": item.get("secure"),
                "httpOnly": item.get("httpOnly"),
                "expires": expires,
                "name": item.get("name"),
                "value": item.get("value"),
                "sameSite": item.get("sameSite"),
            }
        )
    return entries


def parse_cookies(text):
    """Parse either a Netscape cookies.txt or a JSON cookie export.

    Auto-detects the format so the user can paste whatever their extension
    hands them.
    """
    if not text or not text.strip():
        raise AppError(
            "No cookies supplied. Paste a cookies.txt export (Netscape format) "
            "or the JSON export from Cookie-Editor, taken from tiktok.com while "
            "logged in.",
            "no_cookies",
        )

    stripped = text.lstrip()
    if stripped[:1] in "[{":
        entries = _parse_json(stripped)
        if not entries:
            raise AppError(
                "That looks like JSON but no cookies could be read from it. "
                "Paste the raw JSON array from Cookie-Editor, or a Netscape "
                "cookies.txt instead.",
                "no_cookies",
            )
    else:
        entries = _parse_netscape(stripped)

    return _build_cookies(entries)


def parse_netscape_cookies(text):
    """Netscape-only entry point, kept for the test suite."""
    if not text or not text.strip():
        raise AppError("No cookies supplied.", "no_cookies")
    return _build_cookies(_parse_netscape(text))


def cookie_key(cookies_text):
    return hashlib.sha1(cookies_text.encode("utf-8", "replace")).hexdigest()[:16]


def write_jar(cookies_text, key):
    """Write a filtered curl cookie jar and return its path."""
    _cookies, jar_text = parse_cookies(cookies_text)
    jar_path = TEMP_DIR / f"{key}.cookies.txt"
    jar_path.write_text(jar_text, encoding="utf-8")
    return str(jar_path)


def sweep_temp():
    """Drop jars that are older than the cache window."""
    cutoff = time.time() - CACHE_TTL
    for f in TEMP_DIR.glob("*.cookies.txt"):
        try:
            if f.stat().st_mtime < cutoff:
                f.unlink()
        except OSError:
            pass


