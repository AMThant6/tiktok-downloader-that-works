JOBS = {}
JOBS_LOCK = threading.Lock()
JOB_QUEUE = queue.Queue()
JOB_SEQ = [0]


def new_job(url, cookies, gear_index):
    with JOBS_LOCK:
        JOB_SEQ[0] += 1
        job_id = f"j{JOB_SEQ[0]}-{int(time.time())}"
        job = {
            "id": job_id,
            "status": "queued",
            "progress": 0.0,
            "message": "Queued - waiting for the current job to finish.",
            "filename": None,
            "title": None,
            "done_bytes": 0,
            "expected": 0,
            "url": url,
            "cookies": cookies,
            "gear_index": gear_index,
            "code": None,
        }
        JOBS[job_id] = job
    JOB_QUEUE.put(job_id)
    return job_id


def worker():
    while True:
        job_id = JOB_QUEUE.get()
        try:
            with JOBS_LOCK:
                job = JOBS.get(job_id)
            if job is None:
                continue
            process_job(job)
        except Exception as exc:  # noqa: BLE001
            with JOBS_LOCK:
                job = JOBS.get(job_id)
                if job:
                    job["status"] = "error"
                    job["message"] = f"Worker crashed: {exc}"
        finally:
            JOB_QUEUE.task_done()


def job_public(job):
    """Only expose what the UI needs - never echo the cookies back."""
    out = {
        "status": job["status"],
        "progress": round(job["progress"], 1),
        "message": job["message"],
        "filename": job["filename"],
        "title": job["title"],
        "done_bytes": job["done_bytes"],
        "expected": job["expected"],
        "code": job.get("code"),
    }
    if job["status"] == "done" and job.get("file_path"):
        out["file_url"] = f"/api/file/{job['id']}"
    return out


